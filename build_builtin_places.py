def _addr(p):
    parts = [p.get("street"), p.get("housenumber"), p.get("district"),
             p.get("city"), p.get("county"), p.get("state"), p.get("country")]
    return "".join(str(x) for x in parts if x)


def query(name):
    """查一个地名。⚠️ 用 limit=5 再挑，**不要 limit=1**。

    实测：Photon 对"多义名"排第一的往往就是**错的那个** ——
      Macau   → 法国 Gironde 的同名小镇
      七星岩  → 台湾的（还带个"温德姆至尊酒店"的名字）
      少林寺  → 日本福冈的
      泰山    → 新北泰山区的
    所以一次拉 5 条，按"坐标落在中国境内"筛一遍再取第一条。
    （坐标过滤挡不住台湾/福冈这类，所以易混名还要在 FIX 里加限定词。）
    """
    url = "%s?q=%s&limit=5" % (U, urllib.parse.quote(name))
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=25) as r:
                d = json.loads(r.read().decode("utf-8", "replace"))
            for f in (d.get("features") or []):
                try:
                    lon, lat = f["geometry"]["coordinates"][:2]
                    lat, lon = float(lat), float(lon)
                except Exception:
                    continue
                if not (3.0 <= lat <= 54.5 and 73.0 <= lon <= 136.0):
                    continue          # 跑到境外去了
                p = f.get("properties") or {}
                return name, {"name": p.get("name") or name,
                              "lat": round(lat, 6), "lon": round(lon, 6),
                              "addr": _addr(p)}
            return name, None
        except Exception:
            time.sleep(0.6 * (attempt + 1))
    return name, None


